    function rank(el) {
        var sum = el.querySelector("summary");
        var head = sum && sum.firstElementChild;
        var t = String((head ? head.textContent : (sum ? sum.textContent : "")) || "");
        for (var i = 0; i < ORDER.length; i++) if (t.indexOf(ORDER[i]) > -1) return i;
        return ORDER.length;
    }

    function reorder(host, last) {
        var items = [];
        for (var n = host.firstElementChild; n; n = n.nextElementSibling) {
            if (n.matches && n.matches("details.lib-item")) items.push(n);
        }
        // 글 목록 바로 다음 자리(안내 상자 앞)에 순서대로 다시 꽂는다
        var anchor = last ? last.nextSibling : null;
        items.map(function (el, i) { return { el: el, r: rank(el), i: i }; })
             .sort(function (a, b) { return (a.r - b.r) || (a.i - b.i); })
             .forEach(function (x) { host.insertBefore(x.el, anchor); });
    }

